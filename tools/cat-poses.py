#!/usr/bin/env python3
"""Cat poses -> occupancy masks, so she can walk instead of standing still."""
import glob, os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".pylibs"))
from PIL import Image, ImageOps
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
COLS = 64
POSE_ROWS = 48
def main():
    src = os.path.join(ROOT, "public", "gen", "catposes")
    files = sorted(glob.glob(os.path.join(src, "*.png")))
    # a drawing that came out as a solid lump is kept on disk but never used,
    # so the lattice has no pose that reads as a blob
    files = [f for f in files if "dropped" not in os.path.basename(f)]
    masks = []
    for path in files:
        im = ImageOps.exif_transpose(Image.open(path).convert("L"))
        # the drawing is black on white: anything darker than mid is the cat
        bw = im.point(lambda v: 255 if v < 128 else 0)
        box = bw.getbbox()
        if box:
            bw = bw.crop(box)
        # every pose is fitted into the same 64x48 box, so the lattice can blend
        # between them cell by cell without the grid moving under her
        rows = POSE_ROWS
        scale = min(COLS / bw.width, rows / bw.height)
        fitted = bw.resize((max(1, round(bw.width * scale)), max(1, round(bw.height * scale))), Image.LANCZOS)
        canvas = Image.new("L", (COLS, rows), 0)
        canvas.paste(fitted, ((COLS - fitted.width) // 2, rows - fitted.height))
        px = canvas.load()
        grid = ["".join("1" if px[x, y] > 110 else "0" for x in range(COLS)) for y in range(rows)]
        masks.append((rows, grid))
    out = os.path.join(ROOT, "src", "data", "catPoses.ts")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("/**\n * Cat poses as occupancy grids (one string per row, 64 columns),\n * generated by tools/cat-poses.py from public/gen/catposes. The lattice\n * morphs between these, so she can walk and change her shape.\n */\n\n")
        fh.write("export const POSE_COLS = %d;\n\n" % COLS)
        fh.write("export const CAT_POSES: string[][] = [\n")
        for rows, grid in masks:
            fh.write("  [\n")
            for line in grid:
                fh.write('    "%s",\n' % line)
            fh.write("  ],\n")
        fh.write("];\n")
    print("poses", len(masks), "rows", [m[0] for m in masks], "->", out)
    return 0
if __name__ == "__main__":
    sys.exit(main())
