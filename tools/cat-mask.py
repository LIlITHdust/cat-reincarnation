#!/usr/bin/env python3
"""
The cat, as a dot-matrix mask.

The reference language for this film is an instrument console, and a console
draws shapes as grids of lit cells: a matrix of small squares where brightness
carries the information. So the silhouette is rasterised once, here, into run
lengths of columns per row, and shipped as a tiny TypeScript module that the
lattice widget can light up.

Usage: python3 tools/cat-mask.py
"""

import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".pylibs"))

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
COLS = 96


def flatten(d: str, step: int = 60):
    tokens = re.findall(r"[MLCZmlcz]|-?\d*\.?\d+", d)
    i = 0
    cur = (0.0, 0.0)
    start = (0.0, 0.0)
    pts = []

    def num():
        nonlocal i
        value = float(tokens[i])
        i += 1
        return value

    while i < len(tokens):
        command = tokens[i]
        i += 1
        if command == "M":
            cur = (num(), num())
            start = cur
            pts.append(cur)
        elif command == "L":
            cur = (num(), num())
            pts.append(cur)
        elif command == "C":
            c1 = (num(), num())
            c2 = (num(), num())
            to = (num(), num())
            for k in range(1, step + 1):
                t = k / step
                u = 1 - t
                pts.append(
                    (
                        u * u * u * cur[0] + 3 * u * u * t * c1[0] + 3 * u * t * t * c2[0] + t * t * t * to[0],
                        u * u * u * cur[1] + 3 * u * u * t * c1[1] + 3 * u * t * t * c2[1] + t * t * t * to[1],
                    )
                )
            cur = to
        elif command in "Zz":
            pts.append(start)
            cur = start
    return pts


def main() -> int:
    src = open(os.path.join(ROOT, "src", "data", "catForm.ts"), encoding="utf-8").read()
    path = re.search(r'CAT_PATH = "([^"]+)"', src).group(1)
    box = re.search(r"CAT_VIEWBOX = \{ x: ([\d.-]+), y: ([\d.-]+), w: ([\d.-]+), h: ([\d.-]+) \}", src)
    bx, by, bw, bh = (float(box.group(i)) for i in range(1, 5))

    poly = flatten(path)
    rows = round(COLS * bh / bw)

    def inside(x: float, y: float) -> bool:
        hit = False
        n = len(poly)
        for i in range(n):
            x0, y0 = poly[i]
            x1, y1 = poly[(i + 1) % n]
            if (y0 > y) != (y1 > y):
                xin = x0 + (y - y0) * (x1 - x0) / (y1 - y0)
                if x < xin:
                    hit = not hit
        return hit

    grid = []
    for r in range(rows):
        y = by + (r + 0.5) * bh / rows
        line = "".join(
            "1" if inside(bx + (c + 0.5) * bw / COLS, y) else "0" for c in range(COLS)
        )
        grid.append(line)

    runs = []
    for line in grid:
        row = []
        start = None
        for c, cell in enumerate(line + "0"):
            if cell == "1" and start is None:
                start = c
            elif cell == "0" and start is not None:
                row.append((start, c - 1))
                start = None
        runs.append(row)

    body = "\n".join("  [" + ", ".join(f"[{a}, {b}]" for a, b in row) + "]," for row in runs)
    text = f'''/**
 * The cat as a dot matrix: {COLS}×{rows} cells, one run list per row. Generated by
 * tools/cat-mask.py from the public-domain silhouette in public/ref — the shape
 * is never drawn as a picture anywhere in the film, it is lit cell by cell.
 */

export const CAT_MASK = {{ cols: {COLS}, rows: {rows} }};

export const CAT_ROWS: [number, number][][] = [
{body}
];
'''
    out = os.path.join(ROOT, "src", "data", "catMask.ts")
    with open(out, "w", encoding="utf-8") as handle:
        handle.write(text)
    lit = sum(1 for line in grid for ch in line if ch == "1")
    print(f"{COLS}x{rows} cells, {lit} lit ({lit / (COLS * rows) * 100:.0f}%)")
    print(f"wrote {out} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
