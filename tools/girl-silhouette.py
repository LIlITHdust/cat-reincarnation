#!/usr/bin/env python3
"""
Turn the illustration's alpha channel into a coarse density map.

The morph scene needs to know which part of the middle panel belongs to her:
the particles have to converge onto her body, not onto a rectangle. Reading
pixels in the browser is possible but fragile at render time, so the shape is
extracted here once, as runs of occupied cells per row, and shipped as a small
TypeScript module.

Usage: python3 tools/girl-silhouette.py [source.png] [out.ts]
"""

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".pylibs"))

from PIL import Image  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GRID_W = 64
THRESHOLD = 0.42


def main() -> int:
    source = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "public", "char", "girl.png")
    target = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, "src", "data", "girlSilhouette.ts")

    image = Image.open(source).convert("RGBA")
    width, height = image.size
    grid_h = round(GRID_W * height / width)
    alpha = image.getchannel("A")

    rows = []
    for gy in range(grid_h):
        y0 = int(gy * height / grid_h)
        y1 = max(y0 + 1, int((gy + 1) * height / grid_h))
        cells = []
        for gx in range(GRID_W):
            x0 = int(gx * width / GRID_W)
            x1 = max(x0 + 1, int((gx + 1) * width / GRID_W))
            box = alpha.crop((x0, y0, x1, y1))
            total = box.size[0] * box.size[1]
            solid = sum(1 for value in box.getdata() if value > 40)
            cells.append(solid / total > THRESHOLD)

        runs = []
        start = None
        for gx, filled in enumerate(cells + [False]):
            if filled and start is None:
                start = gx
            elif not filled and start is not None:
                runs.append((start, gx - 1))
                start = None
        rows.append(runs)

    occupied = sum(end - start + 1 for row in rows for start, end in row)
    body = "\n".join(
        "  [" + ", ".join(f"[{a}, {b}]" for a, b in row) + "]," for row in rows
    )
    text = f'''/**
 * Her body, as occupancy runs on a {GRID_W}×{grid_h} grid over the
 * illustration. Row order is top to bottom; each pair is an inclusive span of
 * columns. Generated by tools/girl-silhouette.py — do not edit by hand.
 */

export const GIRL_GRID = {{ w: {GRID_W}, h: {grid_h} }};

export const GIRL_ROWS: [number, number][][] = [
{body}
];
'''
    with open(target, "w", encoding="utf-8") as handle:
        handle.write(text)

    print(f"{source} {width}x{height} -> {GRID_W}x{grid_h} grid")
    print(f"rows {grid_h}, runs {sum(len(row) for row in rows)}, covered cells {occupied}")
    print(f"empty rows: {[i for i, row in enumerate(rows) if not row][:8]}")
    print(f"wrote {target} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
